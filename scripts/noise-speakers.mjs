#!/usr/bin/env node
// The noise room's playlist (Jens t872u). Converts a folder of sound files to the streaming format and writes
// client/public/noise-speakers/manifest.json (what client/src/noisespeakers.js plays). Needs ffmpeg + ffprobe.
//
//   node scripts/noise-speakers.mjs <folder>                 convert every audio file in <folder> (adds to the playlist)
//   node scripts/noise-speakers.mjs <folder> --replace       …and drop every track that is not in <folder> (placeholders too)
//   node scripts/noise-speakers.mjs --placeholders           (re)make the 3 short test tones in client/public/noise-speakers/test/
//                                                            (generated by ffmpeg, no files needed; played with ?noiseplaylist=test)
//   options: --bitrate 96k (default; 128k = better, +33 % bandwidth) --no-normalize (keep the files' own loudness)
//            --out <dir> (default client/public/noise-speakers)
//
// Format: MP3, 44.1 kHz stereo, constant 96 kb/s ≈ 0.72 MB a minute – plays on every browser (iPhone Safari
// included), streams with range requests, and the file name carries the content's hash so the server lets
// browsers cache it for good (server/app.js) – a returning player downloads nothing again. Loudness is
// evened out (EBU R128, −16 LUFS, peaks ≤ −1.5 dBTP; two passes, a plain gain change when possible – the dynamics stay) so one track isn't much louder than the next.
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const flag = (k) => args.includes(k);
const OUT = path.resolve(opt('--out', path.join(ROOT, flag('--placeholders') ? 'client/public/noise-speakers/test' : 'client/public/noise-speakers')));
const BITRATE = opt('--bitrate', '96k');
const NORMALIZE = !flag('--no-normalize');
const AUDIO = /\.(mp3|wav|flac|m4a|aac|ogg|oga|opus|aif|aiff|wma|webm|mp4|caf)$/i;
const valued = new Set(['--out', '--bitrate']);
const input = args.find((a, i) => !a.startsWith('--') && !valued.has(args[i - 1]));

const run = (cmd, a) => execFileSync(cmd, a, { stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 << 20 }).toString();
const duration = (f) => Number(run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', f]).trim());
const slug = (s) => s.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48) || 'track';
const manifestPath = path.join(OUT, 'manifest.json');
const readManifest = () => { try { return JSON.parse(fs.readFileSync(manifestPath, 'utf8')); } catch { return { tracks: [] }; } };

// one source (a file, or ffmpeg lavfi input args) → <slug>-<hash8>.mp3 in OUT; returns the manifest entry
function convert(srcArgs, title, tmpDir) {
  const tmp = path.join(tmpDir, crypto.randomBytes(6).toString('hex') + '.mp3');
  // two-pass loudnorm: measure first, then a plain gain change (linear=true) so the music's own dynamics stay as made
  let af = [];
  if (NORMALIZE) {
    const LN = 'loudnorm=I=-16:TP=-1.5:LRA=20';
    af = ['-af', LN];
    const r = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-y', ...srcArgs, '-vn', '-af', LN + ':print_format=json', '-f', 'null', '-'], { maxBuffer: 64 << 20 });
    try {
      const err = String(r.stderr || '');
      const m = JSON.parse(err.slice(err.lastIndexOf('{'), err.lastIndexOf('}') + 1));
      if (Number.isFinite(+m.input_i)) af = ['-af', `${LN}:measured_I=${m.input_i}:measured_TP=${m.input_tp}:measured_LRA=${m.input_lra}:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true`];
    } catch { /* measuring failed: one-pass loudnorm */ }
  }
  run('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...srcArgs, '-vn', '-map_metadata', '-1', ...af,
    '-ac', '2', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', BITRATE, '-write_xing', '1', tmp]);
  const buf = fs.readFileSync(tmp), hash = crypto.createHash('sha1').update(buf).digest('hex').slice(0, 8);
  const file = `${slug(title)}-${hash}.mp3`;
  fs.renameSync(tmp, path.join(OUT, file));
  return { file, title, duration: +duration(path.join(OUT, file)).toFixed(3), bytes: buf.length };
}

function write(tracks) {
  const m = { version: 1, format: 'mp3', bitrate: BITRATE, made: new Date().toISOString(), tracks };
  fs.writeFileSync(manifestPath, JSON.stringify(m, null, 2) + '\n');
  // files in OUT that no track uses any more
  const used = new Set(tracks.map((t) => t.file));
  for (const f of fs.readdirSync(OUT)) if (/\.mp3$/i.test(f) && !used.has(f)) fs.unlinkSync(path.join(OUT, f));
  const mb = tracks.reduce((s, t) => s + t.bytes, 0) / 1e6, min = tracks.reduce((s, t) => s + t.duration, 0) / 60;
  console.log(`${tracks.length} tracks, ${min.toFixed(1)} min, ${mb.toFixed(1)} MB → ${path.relative(ROOT, manifestPath)}`);
}

fs.mkdirSync(OUT, { recursive: true });
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'noise-speakers-'));
try {
  if (flag('--placeholders')) {
    // three short test tones, made by ffmpeg's own generators (no source files): placeholders until Jens's music
    const tones = [
      ['Test tone 1 (A 440)', 'sine=frequency=440:duration=9', 'volume=0.5,apulsator=hz=2:amount=0.7'],
      ['Test tone 2 (E 330)', 'sine=frequency=330:duration=12', 'volume=0.5,tremolo=f=4:d=0.6'],
      ['Test tone 3 (C 523)', 'sine=frequency=523.25:duration=7', 'volume=0.45,apulsator=hz=1:amount=0.5'],
    ];
    const keep = readManifest().tracks.filter((t) => !t.placeholder);
    const made = tones.map(([title, src, fx]) => ({ ...convert(['-f', 'lavfi', '-i', src, '-af', fx], title, tmpDir), placeholder: true }));
    write([...keep, ...made]);
  } else if (input) {
    const dir = path.resolve(input);
    const files = fs.readdirSync(dir).filter((f) => AUDIO.test(f)).sort((a, b) => a.localeCompare(b));
    if (!files.length) { console.error(`no audio files in ${dir}`); process.exit(1); }
    const old = flag('--replace') ? [] : readManifest().tracks.filter((t) => !t.placeholder); // real music replaces the test tones
    const made = [];
    for (const f of files) {
      process.stdout.write(`  ${f} … `);
      try { const t = convert(['-i', path.join(dir, f)], path.parse(f).name, tmpDir); made.push(t); console.log(`${t.duration.toFixed(0)} s, ${(t.bytes / 1e6).toFixed(1)} MB`); }
      catch (e) { console.log('skipped (' + String(e.stderr || e.message).trim().split('\n').pop() + ')'); }
    }
    const byFile = new Map([...old, ...made].map((t) => [t.file, t])); // same content twice → once
    write([...byFile.values()]);
  } else {
    console.log('usage: node scripts/noise-speakers.mjs <folder> [--replace] [--bitrate 96k] | --placeholders');
    process.exit(1);
  }
} finally { fs.rmSync(tmpDir, { recursive: true, force: true }); }
